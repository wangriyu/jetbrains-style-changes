let chinese = false;

function setLanguage(language) {
    chinese = String(language || 'en').toLowerCase().startsWith('zh');
}

function t(source, ...args) {
    const template = chinese && Object.prototype.hasOwnProperty.call(zh, source) ? zh[source] : source;
    return template.replace(/\{(\d+)\}/g, (placeholder, index) =>
        Number(index) < args.length ? String(args[Number(index)]) : placeholder);
}

module.exports = { t, setLanguage };
